#!/usr/bin/env python3
"""Write results/basepaper/SUMMARY.md from the saved JSON (plan R6).

  make_summary.py [--dir results/basepaper]

Every number in SUMMARY.md is computed here from the files under --dir (summary.json files
written by bp_eval.py, plus the raw rb4 masks), and each claim row names its sources. The
verdict wording is written by hand below; each statement the wording relies on is checked by an
assert, so the text cannot drift from the data: if the data changes so that a sentence is no
longer true, this script fails instead of printing it. Standard library only."""
import argparse
import json
import os
import re
import sys

CATS = ["EMAIL", "PHONE", "QUESTION", "GREETING", "NAME"]


def sp(x, scale=1.0, nd=3):
    """'median [min..max]' with scale applied."""
    f = lambda v: f"{v * scale:.{nd}g}"
    return f"{f(x['median'])} [{f(x['min'])}..{f(x['max'])}]"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--dir", default="results/basepaper")
    d = ap.parse_args().dir
    J = lambda p: json.load(open(os.path.join(d, p)))
    rb1, rb2, rb3, rb5 = J("rb1/summary.json"), J("rb2/summary.json"), J("rb3/summary.json"), J("rb5/summary.json")
    rb4 = J("rb4/summary.json")
    machine = open(os.path.join(d, "machine.txt")).read()
    head = machine.splitlines()
    runs = int(re.search(r"runs per point: (\d+)", head[0]).group(1))
    assert "smoke" not in head[0] and runs >= 5, "SUMMARY.md must come from a full run with >= 5 runs per point"

    # ---- lookups ---------------------------------------------------------------------------
    r1 = {(r["input_index"], r["variant"]): r for r in rb1}
    r2 = {(r["variant"], r["batch"]): r["inputs_per_s"] for r in rb2}
    r3 = {(r["variant"], r["k"]): r for r in rb3}
    r5 = {r["variant"]: r for r in rb5 if "variant" in r}
    inputs = {i: r1[(i, "fork")]["input"] for i in range(1, 6)}
    paper41 = {1: (8.9, 3.7), 2: (7.2, 2.9), 3: (6.8, 2.8), 4: (6.5, 2.7), 5: (7.1, 3.0)}   # base paper §4.1 (seq ms, par ms)

    out = []
    w = out.append
    w("# Base-paper reproduction: results summary\n")
    w("Generated by `tools/basepaper/make_summary.py` from the saved runs in this directory "
      f"({runs} runs per point; machine and commit in `machine.txt`). Nothing here was tuned to match the "
      "paper; where we differ from it, that is the finding. The paper's dataset is not available, so "
      "accuracy is compared by trend only.\n")
    model = re.search(r"Model name:\s+(.*)", machine).group(1).strip()
    nphys = re.search(r"physical cores: (\d+)", machine).group(1)
    gccv = re.search(r"gcc \(.*\) (\S+)", machine).group(1)
    w(f"Machine: {model}, {nphys} physical cores "
      "(a hybrid CPU: 6 performance cores with SMT, then 8 efficiency cores), Linux, "
      f"gcc {gccv}, `-O2`. Commit {head[1].split()[1][:12]}.\n")

    # ---- claim 6: single-input latency -------------------------------------------------------
    fork_p50 = [r1[(i, "fork")]["p50_ns"] for i in range(1, 6)]
    rec_p50 = [r1[(i, "seq-recompile")]["p50_ns"] for i in range(1, 6)]
    pre_p50 = [r1[(i, "seq-precompiled")]["p50_ns"] for i in range(1, 6)]
    lo = min(x["min"] for x in fork_p50); hi = max(x["max"] for x in fork_p50)
    assert hi < 3.7e6 and lo > 1e5, "fork latency left the range the verdict text describes"
    rec_lo = min(x["min"] for x in rec_p50); rec_hi = max(x["max"] for x in rec_p50)
    assert all(f["min"] > 5 * s["max"] for f, s in zip(fork_p50, rec_p50)), "fork is not >5x slower than seq-recompile"
    f1 = r1[(1, "fork")]
    assert max(x["max"] for x in pre_p50) < 1000, "seq-precompiled median latency is no longer under 1 microsecond"
    # per-input ratios against the paper's table (paper parallel ms / our fork ms; our fork / our seq-recompile)
    faster = [paper41[i][1] * 1e6 / fork_p50[i - 1]["median"] for i in range(1, 6)]
    slower = [fork_p50[i]["median"] / rec_p50[i]["median"] for i in range(5)]
    assert min(faster) > 10 and min(slower) > 5
    assert f1["mean_child_regexec_ns"]["median"] < 0.05 * f1["mean_fork_to_collect_ns"]["median"]
    assert f1["mean_child_regcomp_ns"]["median"] < 0.2 * f1["mean_fork_to_collect_ns"]["median"]

    # ---- claim 2: batches --------------------------------------------------------------------
    sizes = sorted({b for (v, b) in r2 if v == "fork"})
    assert all(r2[("fork", b)]["median"] < r2[("seq-recompile", b)]["median"] for b in sizes)
    assert all(r2[("fork", b)]["median"] < r2[("seq-precompiled", b)]["median"] for b in sizes)
    assert r2[("fork", 10)]["median"] > 1.5 * r2[("fork", 1)]["median"]
    flat = [r2[("fork", b)]["median"] for b in sizes if b >= 10]
    assert max(flat) < 1.1 * min(flat), "fork throughput is not flat for batches >= 10"

    # ---- claim 3: scaling --------------------------------------------------------------------
    ks = sorted({k for (v, k) in r3 if v == "fork"})
    maxk = lambda v: max(r3[(v, k)]["speedup_vs_same_variant_k1"] for k in ks)
    assert r3[("dfa", 8)]["cpus"] == [0, 2, 4, 6, 8, 10, 12, 13], "k=8 no longer uses 2 efficiency cores (12, 13)"
    assert maxk("fork") < 5 and maxk("threads-pattern") < 5
    assert r3[("threads-data", 6)]["speedup_vs_same_variant_k1"] > 4 and r3[("dfa", 6)]["speedup_vs_same_variant_k1"] > 5
    assert r3[("threads-data", 8)]["speedup_vs_same_variant_k1"] < r3[("threads-data", 6)]["speedup_vs_same_variant_k1"]
    over5 = sorted({(r["variant"], r["k"]) for r in rb3 if r["variant"] != "seq-precompiled"
                    and r["speedup_vs_same_variant_k1"] > 5})
    assert all(v == "dfa" for v, _ in over5), over5

    # ---- claim 1: parallel regexes help ------------------------------------------------------
    big = max(sizes)
    assert r2[("threads-pattern", big)]["median"] < r2[("seq-precompiled", big)]["median"]
    assert r2[("threads-data_t5", big)]["median"] > 2 * r2[("seq-precompiled", big)]["median"]
    assert r2[("dfa_t5", big)]["median"] > 10 * r2[("seq-precompiled", big)]["median"]

    # ---- claim 4: accuracy -------------------------------------------------------------------
    A = {m: rb4[m] for m in ("none", "paper")}
    grp = {m: A[m]["label_accuracy_by_group"] for m in A}
    S, N = "structured (EMAIL, PHONE)", "natural language (QUESTION, GREETING)"
    assert grp["none"][S] > grp["none"][N], "structured is not more accurate than natural language under none"
    assert grp["paper"][S] < grp["paper"][N], "the reversal under the paper's input module is gone"
    assert A["paper"]["per_category"]["NAME"]["tp"] == 0

    # ---- claim 5: multi-label share ----------------------------------------------------------
    masks = [l.strip() for l in open(os.path.join(d, "rb4/masks_none.txt"))]
    multi_pred = sum(1 for m in masks if m.count("1") >= 2)
    truth_multi = 0
    for line in open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "../../tests/basepaper/labeled.tsv"),
                     encoding="utf-8"):
        if not line.startswith("#") and "," in line.split("\t")[1]:
            truth_multi += 1
    n = len(masks)

    # ---- claim table -------------------------------------------------------------------------
    w("## Claims of the base paper\n")
    w("Claim numbers follow `docs/research/literature_review.md` §3. Values are medians over runs with "
      "[min..max] in brackets.\n")
    w("| # | Claim (paper) | Paper's figure | Our measurement | Verdict | Why |")
    w("|---|---|---|---|---|---|")
    w(f"| 1 | Parallel regex matchers speed up classification (§1, §3.3) | 2.4× over sequential | "
      f"`fork` (the paper's design) vs sequential at {big:,} inputs: {r2[('fork', big)]['median'] / r2[('seq-recompile', big)]['median']:.2f}× "
      f"vs `seq-recompile`, {r2[('fork', big)]['median'] / r2[('seq-precompiled', big)]['median']:.4f}× vs `seq-precompiled`. "
      f"`threads-pattern`: {r2[('threads-pattern', big)]['median'] / r2[('seq-precompiled', big)]['median']:.2f}× vs `seq-precompiled`. "
      f"`threads-data` (5 threads): {r2[('threads-data_t5', big)]['median'] / r2[('seq-precompiled', big)]['median']:.1f}×; "
      f"`dfa` (5 threads): {r2[('dfa_t5', big)]['median'] / r2[('seq-precompiled', big)]['median']:.0f}× | "
      "**Not reproduced** for per-pattern parallelism; supported for data parallelism and the combined DFA | "
      "Splitting one input's five patterns over processes or threads costs more than the matching it saves "
      "(five `regexec` calls on a precompiled set take under a microsecond). Parallelism pays when it splits the inputs, and most "
      "when one DFA checks all patterns in one pass. |")
    w(f"| 2 | Per-input process creation limits small batches; ~10+ inputs work better (§5.3) | speedup needs batches above ~10 | "
      f"`fork` inputs/s: batch 1 {sp(r2[('fork', 1)], nd=4)}, batch 10 {sp(r2[('fork', 10)], nd=4)}, "
      f"batch {big:,} {sp(r2[('fork', big)], nd=4)}; never above `seq-recompile` "
      f"({sp(r2[('seq-recompile', big)], nd=4)} at {big:,}) | **Partly reproduced** | "
      f"Throughput rises {r2[('fork', 10)]['median'] / r2[('fork', 1)]['median']:.1f}× from 1 to 10 inputs, then stays flat, but `fork` is below both sequential "
      "baselines at every batch size. The cost is paid per input (five forks each), so a bigger batch "
      "cannot amortise it. |")
    w(f"| 3 | Near-linear scaling to 6 cores, 5.62× at 8 (§4.3) | 1.92× at 2, 3.48× at 4, 4.87× at 6, 5.62× at 8 | "
      f"`fork` speedup vs itself on 1 core: " + ", ".join(f"{k}: {r3[('fork', k)]['speedup_vs_same_variant_k1']:.2f}" for k in ks[1:]) +
      "; `threads-pattern`: " + ", ".join(f"{k}: {r3[('threads-pattern', k)]['speedup_vs_same_variant_k1']:.2f}" for k in ks[1:]) +
      "; `threads-data`: " + ", ".join(f"{k}: {r3[('threads-data', k)]['speedup_vs_same_variant_k1']:.2f}" for k in ks[1:]) +
      " (cores in the order 2, 4, 6, 8) | **Not reproduced** for the paper's design; reproduced in shape for data parallelism | "
      f"Pattern parallelism cannot exceed 5× with 5 patterns, and `fork` peaks at {maxk('fork'):.2f}× and `threads-pattern` at "
      f"{maxk('threads-pattern'):.2f}×. Splitting the inputs scales near-linearly to 4–6 cores "
      f"(`threads-data` {r3[('threads-data', 6)]['speedup_vs_same_variant_k1']:.2f}× at 6); at 8 it drops because cores 7 and 8 here are slower efficiency cores. "
      "Only `dfa` (a data-parallel variant) exceeds 5×: " + ", ".join(f"{v} at {k} cores = {r3[(v, k)]['speedup_vs_same_variant_k1']:.2f}×" for v, k in over5) + ". |")
    w(f"| 4 | Structured formats are classified more accurately than natural-language ones (§4.2) | email/phone 98.7%, questions/greetings 93.2% | "
      f"Per-label decision accuracy on our 1,250-line labeled set, no normalisation: EMAIL+PHONE {grp['none'][S]:.3f}, "
      f"QUESTION+GREETING {grp['none'][N]:.3f}. With the paper's input module: {grp['paper'][S]:.3f} vs {grp['paper'][N]:.3f} | "
      "**Qualitatively supported** (as typed); reversed with the paper's input module | "
      "Without normalisation the order matches the paper (EMAIL F1 "
      f"{A['none']['per_category']['EMAIL']['f1']:.3f} vs QUESTION {A['none']['per_category']['QUESTION']['f1']:.3f} and GREETING {A['none']['per_category']['GREETING']['f1']:.3f}), "
      f"though PHONE ({A['none']['per_category']['PHONE']['f1']:.3f}) is close to them. The paper's character whitelist rejects "
      f"{A['paper']['rejected_by_input_module']} of the {A['paper']['lines']} lines (for example `+`, `'`) and lowercasing makes the NAME pattern "
      "impossible (0 true positives), which drops EMAIL and PHONE recall. Absolute values depend on our templates. |")
    w(f"| 5 | Single-winner conflict resolution, weights 0.4/0.3/0.3, confidence score (§3.4) | 85–98% confidence in the §4.4 table | "
      f"Not run (R5 not done). The case it matters for is common here: {truth_multi} of {n} labeled lines truly belong to 2+ categories, "
      f"and the five patterns fire together on {multi_pred} lines | **Not tested** | "
      "A single winner would discard the other labels on those lines. The paper's scoring functions are undefined, so reproducing the §4.4 table needs the optional task R5. |")
    w(f"| 6 | 8.9 ms sequential vs 3.7 ms parallel for a short input (§4.1) | 8.9 ms / 3.7 ms for `john@example.com` | "
      f"`fork` per-input latency: {sp(fork_p50[0], 1e-6)} ms for `{inputs[1]}`, {lo / 1e6:.3g}–{hi / 1e6:.3g} ms across the five inputs; "
      f"`seq-recompile`: {rec_lo / 1e6:.3g}–{rec_hi / 1e6:.3g} ms; `seq-precompiled`: {min(x['min'] for x in pre_p50) / 1e6:.2g}–{max(x['max'] for x in pre_p50) / 1e6:.2g} ms | "
      "**Not reproduced** | "
      f"Our `fork` version is {min(faster):.0f}–{max(faster):.0f} times faster than the paper's parallel time for the same input (different machine), but "
      f"{min(slower):.0f}–{max(slower):.0f}× slower than the recompiling sequential loop it was meant to beat "
      f"(paper: 2.4× faster). The paper's hypothesis that process overhead dominates holds: in each child `regcomp` takes about {f1['mean_child_regcomp_ns']['median'] / 1e3:.0f} µs "
      f"and `regexec` about {f1['mean_child_regexec_ns']['median'] / 1e3:.0f} µs, out of {f1['mean_fork_to_collect_ns']['median'] / 1e3:.0f} µs from first fork to last `waitpid`. |")
    w("")

    # ---- details -----------------------------------------------------------------------------
    w("## Detail tables\n")
    w("### RB1 single-input latency (`rb1/summary.json`), p50 per run, µs; 1,000 repetitions per run\n")
    vs = ["fork", "seq-recompile", "seq-precompiled", "threads-pattern", "threads-data_t1", "dfa_t1"]
    w("| input | paper seq / par (ms) | " + " | ".join(vs) + " |")
    w("|---|---|" + "---|" * len(vs))
    for i in range(1, 6):
        w(f"| `{inputs[i]}` | {paper41[i][0]} / {paper41[i][1]} | " + " | ".join(sp(r1[(i, v)]["p50_ns"], 1e-3) for v in vs) + " |")
    w("\n`fork` breakdown (medians over runs): first fork to last waitpid / child regcomp / child regexec, µs\n")
    w("| input | fork to collect | regcomp | regexec |")
    w("|---|---|---|---|")
    for i in range(1, 6):
        r = r1[(i, "fork")]
        w(f"| `{inputs[i]}` | {sp(r['mean_fork_to_collect_ns'], 1e-3)} | {sp(r['mean_child_regcomp_ns'], 1e-3)} | {sp(r['mean_child_regexec_ns'], 1e-3)} |")
    w("\nNote: `seq-precompiled` shows two clusters for some inputs because that variant's single thread is not pinned and the "
      "scheduler can place it on a slower efficiency core; the pinned variants do not.\n")
    w("### RB2 throughput by batch size (`rb2/summary.json`), inputs/s\n")
    v2 = ["fork", "seq-recompile", "seq-precompiled", "threads-pattern", "threads-data_t5", "dfa_t5"]
    w("| batch | " + " | ".join(v2) + " |")
    w("|---|" + "---|" * len(v2))
    for b in sizes:
        w(f"| {b:,} | " + " | ".join(sp(r2[(v, b)], nd=4) for v in v2) + " |")
    w("\nFor batches of 1 to 100 the thread variants measure mostly the wake-up and join latency of their worker threads "
      "(setup is excluded, thread start is not hidden), which is why their min..max ranges are wide.")
    w("\n### RB3 core scaling (`rb3/summary.json`)\n")
    w("CPUs used per k are in each JSON (`cpus`): the first logical CPU of each physical core, in core order; k = 7, 8 include efficiency cores. "
      "Speedup = median inputs/s over the same variant's median at 1 core (and over `seq-precompiled` at 1 core).\n")
    w("| variant | k | inputs per run | inputs/s | vs same variant, 1 core | vs seq-precompiled |")
    w("|---|---|---|---|---|---|")
    for r in rb3:
        w(f"| {r['variant']} | {r['k']} | {r['inputs']:,} | {sp(r['inputs_per_s'], nd=4)} | "
          f"{r['speedup_vs_same_variant_k1']:.2f} | {r['speedup_vs_seq_precompiled']:.3f} |")
    w(f"\nVariants whose speedup over their own 1-core run exceeds 5 (the number of patterns): "
      + (", ".join(f"{v} at {k} cores" for v, k in over5) or "none") + ".\n")
    w("### RB4 accuracy (`rb4/accuracy_none.json`, `rb4/accuracy_paper.json`)\n")
    w("Ground truth describes what each line is (`gen_bp.py`), so lines such as `Hello everyone`, `john smith` and `what is your name` count against the paper's case-sensitive patterns on purpose. Deterministic, so a single run.\n")
    w("| category | normalize=none P / R / F1 | normalize=paper P / R / F1 |")
    w("|---|---|---|")
    fmt = lambda v: "n/a" if v is None else f"{v:.3f}"
    for c in CATS:
        a, b = A["none"]["per_category"][c], A["paper"]["per_category"][c]
        w(f"| {c} | {fmt(a['precision'])} / {fmt(a['recall'])} / {fmt(a['f1'])} | {fmt(b['precision'])} / {fmt(b['recall'])} / {fmt(b['f1'])} |")
    for m in ("none", "paper"):
        o = A[m]["overall"]
        w(f"\n- normalize={m}: exact-match accuracy {o['exact_match_accuracy']:.3f}, per-label accuracy {o['label_accuracy']:.3f}, "
          f"macro F1 {o['macro_f1']:.3f}, lines rejected by the input module: {A[m]['rejected_by_input_module']}")
    w("\n### RB5 kernel vs user time (`rb5/summary.json`), 10,000 inputs\n")
    w("`perf stat` is not permitted on this machine (`perf_event_paranoid=4`, see `rb5/perf_unavailable.txt`), so these come from `/usr/bin/time -v` "
      "(whole process tree) and `getrusage` (same run, in the JSON). CPU migrations are therefore not available.\n")
    w("| variant | wall s | user s (time -v) | sys s (time -v) | voluntary ctx switches | involuntary ctx switches | minor page faults |")
    w("|---|---|---|---|---|---|---|")
    for v in ("fork", "seq-recompile"):
        r = r5[v]
        w(f"| {v} | {sp(r['total_seconds'])} | {sp(r['time_v_user_s'])} | {sp(r['time_v_sys_s'])} | "
          f"{sp(r['time_v_voluntary_ctxt_switches'], nd=4)} | {sp(r['time_v_involuntary_ctxt_switches'], nd=4)} | {sp(r['time_v_minor_faults'], nd=4)} |")
    fr, sr = r5["fork"], r5["seq-recompile"]
    assert fr["time_v_sys_s"]["median"] > 10 * max(sr["time_v_sys_s"]["median"], 0.01)
    w(f"\n`fork` spends {fr['time_v_sys_s']['median']:.2f} s in the kernel against {sr['time_v_sys_s']['median']:.2f} s for the same work without `fork`, "
      f"and {fr['time_v_user_s']['median'] / sr['time_v_user_s']['median']:.0f}× the user time, for the same {fr['inputs']:,} inputs.\n")

    w("## How this was produced\n")
    w("```")
    w("make bp                                   # bin/bp_fork, bin/bp_bench")
    w("tools/basepaper/run_bp.sh --full           # raw JSON, machine.txt, summaries, figures")
    w("python3 tools/basepaper/make_summary.py    # this file")
    w("```")
    w("\nFigures: `figures/rb1.svg` … `rb5.svg`, `rb3_vs_seq.svg`. Raw runs: `rb1/` … `rb5/`. Inputs: `tests/basepaper/` "
      "(`table41.txt`, `labeled.tsv`, generated by `tools/basepaper/gen_bp.py`). Variants are described in `docs/project_design.md` §10.4.\n")
    w("Limits: one machine, one hybrid CPU; the paper's dataset and machine (i7-10750H) are not available; the paper's pattern list is reproduced verbatim "
      "but its input text for timings is a handful of strings. Interpretations we had to choose (character-list reading of `ALLOWED_CHARS`, "
      "pinning inside the allowed CPU set, wording of the per-core output lines) are in `docs/progress.md`.\n")
    w("## Machine\n")
    w("```")
    w("\n".join(l for l in machine.splitlines() if l.strip() and not l.startswith("## per-CPU")
                and not re.match(r"^\d+,\d+,\d+,", l))[:6000])
    w("```")
    text = "\n".join(out) + "\n"
    with open(os.path.join(d, "SUMMARY.md"), "w") as f:
        f.write(text)
    print(f"make_summary: wrote {d}/SUMMARY.md ({len(text.splitlines())} lines)", file=sys.stderr)


if __name__ == "__main__":
    main()
