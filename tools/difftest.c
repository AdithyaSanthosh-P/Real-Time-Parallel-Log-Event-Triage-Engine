/* difftest: differential test of the DFA engine against glibc regexec
 * (spec §3.5, plan T2.5).
 *
 * For every line of the given files (normalized exactly as the pipeline
 * does), and optionally for N generated strings, the rule mask computed by
 * our compiler's DFA must equal the mask from running regexec() per rule
 * (REG_EXTENDED, plus REG_ICASE where the rule says so). Every mismatch is
 * printed with the rule id(s), the line number and the line. Exit status 1
 * if there was any mismatch, 2 on usage or setup errors.
 *
 * usage: difftest [-r RULES] [--max-states N] [--random N] [--seed S] [FILE ...]
 *
 * --random N generates N strings, mixing three kinds:
 *   - a random walk through one rule's AST (a string the rule matches),
 *     usually mutated (bytes replaced, inserted, deleted) and embedded in
 *     random text, which produces near-misses at every boundary;
 *   - fragments of the rules' literal text glued with digits and noise;
 *   - plain random bytes.
 * Generated bytes are restricted to what can survive normalization: tab,
 * 0x20-0x7e and 0x80-0xff (no NUL, no newline, no other control bytes). */

#include <stdio.h>
#include <stdlib.h>
#include <string.h>

#include "ast.h"
#include "batch.h"
#include "engine_dfa.h"
#include "engine_posix.h"
#include "reader.h"
#include "regex_parse.h"
#include "rules.h"

#define MAX_LEN 400
#define MAX_PRINT 20

static RuleSet rs;
static EngineDfa *dfa;
static EnginePosix *posix;
static unsigned long long mismatches, checked;
static unsigned long long rule_hits[RULES_MAX], any_hits;   /* random strings only */

/* ---- random numbers (xorshift64*) ---- */

static uint64_t rng_s = 88172645463325252ull;
static uint64_t rng(void)
{
    rng_s ^= rng_s >> 12;
    rng_s ^= rng_s << 25;
    rng_s ^= rng_s >> 27;
    return rng_s * 2685821657736338717ull;
}
static unsigned rnd(unsigned n) { return n ? (unsigned)(rng() % n) : 0; }

/* A byte that normalization lets through. */
static unsigned char allowed_byte(void)
{
    unsigned r = rnd(100);
    if (r < 3)  return '\t';
    if (r < 90) return (unsigned char)(0x20 + rnd(0x7f - 0x20));
    return (unsigned char)(0x80 + rnd(0x80));
}
static bool is_allowed(unsigned c) { return c == '\t' || (c >= 0x20 && c != 0x7f); }

/* ---- comparison ---- */

static void report(const char *where, unsigned long long lineno, const char *s, size_t n,
                   uint64_t got, uint64_t want)
{
    mismatches++;
    if (mismatches > MAX_PRINT)
        return;
    printf("MISMATCH %s:%llu:", where, lineno);
    for (int r = 0; r < rs.count; r++)
        if (((got ^ want) >> r) & 1)
            printf(" %s(dfa=%d,regexec=%d)", rs.rules[r].id, (int)((got >> r) & 1),
                   (int)((want >> r) & 1));
    printf("\n  line: \"");
    for (size_t i = 0; i < n; i++) {
        unsigned char c = (unsigned char)s[i];
        if (c >= 0x20 && c < 0x7f && c != '"' && c != '\\')
            putchar(c);
        else
            printf("\\x%02x", c);
    }
    printf("\"\n");
}

static void check(const char *where, unsigned long long lineno, const char *s, size_t n)
{
    uint64_t got = dfa_engine_match(dfa, s, n);
    uint64_t want = posix_match(posix, s, n);
    checked++;
    if (got != want)
        report(where, lineno, s, n, got, want);
}

static int check_file(const char *path)
{
    Reader *r = reader_open_path(path, 0);
    if (!r) {
        perror(path);
        return -1;
    }
    Batch b;
    if (batch_init(&b) != 0) {
        reader_close(r);
        return -1;
    }
    int n;
    while ((n = reader_next_batch(r, &b, 256)) > 0)
        for (uint32_t i = 0; i < b.count; i++)
            check(path, b.seq_start + i + 1, batch_norm(&b, i), batch_norm_len(&b, i));
    batch_free(&b);
    reader_close(r);
    if (n < 0) {
        perror(path);
        return -1;
    }
    return 0;
}

/* ---- generation ---- */

typedef struct {
    char   buf[MAX_LEN];
    size_t n;
} Gen;

static void put(Gen *g, unsigned char c)
{
    if (g->n < MAX_LEN)
        g->buf[g->n++] = (char)c;
}

/* A byte of the set, preferring printable ones; 0 bytes in the set = skip. */
static void put_from_set(Gen *g, const CharSet *set)
{
    int count = cs_count(set);
    if (count == 0)
        return;
    for (int tries = 0; tries < 8; tries++) {
        unsigned c = rnd(256);
        if (cs_has(set, (unsigned char)c) && is_allowed(c)) {
            put(g, (unsigned char)c);
            return;
        }
    }
    int k = (int)rnd((unsigned)count);           /* exact pick among members */
    for (unsigned c = 0; c < 256; c++) {
        if (cs_has(set, (unsigned char)c) && k-- == 0) {
            put(g, is_allowed(c) ? (unsigned char)c : (unsigned char)' ');
            return;
        }
    }
}

/* Random walk through the AST: emits a string the regex matches (modulo the
 * byte restriction). Repeat counts are kept small. */
static void walk(Gen *g, const AstNode *n)
{
    switch (n->kind) {
    case NODE_CHARSET:
        put_from_set(g, &n->set);
        break;
    case NODE_CONCAT:
        for (int i = 0; i < n->nkids; i++)
            walk(g, n->kids[i]);
        break;
    case NODE_ALT:
        walk(g, n->kids[rnd((unsigned)n->nkids)]);
        break;
    case NODE_STAR:
        for (unsigned k = rnd(4); k > 0; k--)
            walk(g, n->kids[0]);
        break;
    case NODE_PLUS:
        for (unsigned k = 1 + rnd(3); k > 0; k--)
            walk(g, n->kids[0]);
        break;
    case NODE_QUEST:
        if (rnd(2))
            walk(g, n->kids[0]);
        break;
    case NODE_REPEAT: {
        int hi = n->max == REPEAT_INF ? n->min + 3 : n->max;
        int k = n->min + (int)rnd((unsigned)(hi - n->min + 1));
        /* sometimes one short or one long, to probe the bounds */
        if (rnd(8) == 0 && k > 0) k--;
        else if (rnd(8) == 0) k++;
        for (int i = 0; i < k; i++)
            walk(g, n->kids[0]);
        break;
    }
    case NODE_BOL:
    case NODE_EOL:
        break;
    }
}

static AstNode *asts[RULES_MAX];

/* Literal fragments of the rules: maximal runs of plain characters. */
static char frags[512][32];
static int nfrags;

static void collect_fragments(void)
{
    for (int r = 0; r < rs.count && nfrags < 512; r++) {
        const char *re = rs.rules[r].regex;
        char cur[32];
        size_t k = 0;
        for (const char *p = re;; p++) {
            bool plain = *p && !strchr("()[]{}|*+?.^$\\", *p);
            if (plain && k < sizeof cur - 1) {
                cur[k++] = *p;
                continue;
            }
            if (k >= 2 && nfrags < 512) {
                cur[k] = '\0';
                strcpy(frags[nfrags++], cur);
            }
            k = 0;
            if (!*p)
                break;
        }
    }
}

static void noise(Gen *g, unsigned max)
{
    for (unsigned k = rnd(max + 1); k > 0; k--)
        put(g, allowed_byte());
}

static void mutate(Gen *g)
{
    for (unsigned m = 1 + rnd(3); m > 0 && g->n > 0; m--) {
        size_t at = rnd((unsigned)g->n);
        switch (rnd(3)) {
        case 0:                                   /* replace */
            g->buf[at] = (char)allowed_byte();
            break;
        case 1:                                   /* delete */
            memmove(g->buf + at, g->buf + at + 1, g->n - at - 1);
            g->n--;
            break;
        default:                                  /* insert */
            if (g->n < MAX_LEN) {
                memmove(g->buf + at + 1, g->buf + at, g->n - at);
                g->buf[at] = (char)allowed_byte();
                g->n++;
            }
        }
    }
}

static void generate(Gen *g)
{
    g->n = 0;
    unsigned kind = rnd(10);
    if (kind < 6) {                               /* rule-derived */
        if (rnd(2))
            noise(g, 12);
        walk(g, asts[rnd((unsigned)rs.count)]);
        if (rnd(4))
            mutate(g);
        if (rnd(3) == 0)                          /* two rules on one line */
            walk(g, asts[rnd((unsigned)rs.count)]);
        if (rnd(2))
            noise(g, 12);
    } else if (kind < 9 && nfrags > 0) {          /* fragment mix */
        for (unsigned parts = 1 + rnd(6); parts > 0; parts--) {
            switch (rnd(4)) {
            case 0: case 1: {
                const char *f = frags[rnd((unsigned)nfrags)];
                for (const char *p = f; *p; p++)
                    put(g, (unsigned char)*p);
                break;
            }
            case 2:
                for (unsigned d = 1 + rnd(16); d > 0; d--)
                    put(g, (unsigned char)('0' + rnd(10)));
                break;
            default:
                noise(g, 4);
            }
        }
    } else {                                      /* random bytes */
        noise(g, 60);
    }
}

/* ---- main ---- */

static void usage(void)
{
    fprintf(stderr, "usage: difftest [-r RULES] [--max-states N] [--random N] [--seed S] [FILE ...]\n");
    exit(2);
}

int main(int argc, char **argv)
{
    const char *rules_path = "rules/default.rules";
    long random_n = 0, max_states = 0;
    unsigned long long seed = 1;
    const char *files[256];
    int nfiles = 0;

    for (int i = 1; i < argc; i++) {
        if (strcmp(argv[i], "-r") == 0 && i + 1 < argc)
            rules_path = argv[++i];
        else if (strcmp(argv[i], "--random") == 0 && i + 1 < argc)
            random_n = strtol(argv[++i], NULL, 10);
        else if (strcmp(argv[i], "--seed") == 0 && i + 1 < argc)
            seed = strtoull(argv[++i], NULL, 10);
        else if (strcmp(argv[i], "--max-states") == 0 && i + 1 < argc)
            max_states = strtol(argv[++i], NULL, 10);
        else if (argv[i][0] == '-')
            usage();
        else if (nfiles < 256)
            files[nfiles++] = argv[i];
    }
    if (nfiles == 0 && random_n <= 0)
        usage();

    char err[512];
    if (rules_load(rules_path, &rs, err, sizeof err) != 0) {
        fprintf(stderr, "difftest: %s\n", err);
        return 2;
    }
    dfa = dfa_engine_build(&rs, (int)max_states, err, sizeof err);
    posix = dfa ? posix_new(&rs, err, sizeof err) : NULL;
    if (!dfa || !posix) {
        fprintf(stderr, "difftest: %s\n", err);
        return 2;
    }
    fprintf(stderr, "difftest: %s: %d rules, %d DFA group(s), %lld DFA states\n", rules_path,
            rs.count, dfa->dfas.ngroups, (long long)dfa->dfas.total_states);

    int status = 0;
    unsigned long long file_lines = 0;
    for (int f = 0; f < nfiles; f++) {
        unsigned long long before = checked;
        if (check_file(files[f]) != 0)
            status = 2;
        file_lines += checked - before;
    }

    if (random_n > 0) {
        rng_s ^= seed * 0x9e3779b97f4a7c15ull;
        if (rng_s == 0)
            rng_s = 1;
        for (int r = 0; r < rs.count; r++) {
            RegexError re;
            asts[r] = regex_parse(rs.rules[r].regex, strlen(rs.rules[r].regex), rs.rules[r].icase, &re);
        }
        collect_fragments();
        Gen g;
        for (long i = 0; i < random_n; i++) {
            generate(&g);
            check("random", (unsigned long long)i + 1, g.buf, g.n);
            uint64_t m = posix_match(posix, g.buf, g.n);
            any_hits += m != 0;
            for (int r = 0; r < rs.count; r++)
                rule_hits[r] += (m >> r) & 1;
        }
        /* Coverage: a zero here means the generator never reached that rule's
         * accept state, so the comparison says little about it. */
        printf("difftest: %.1f%% of random strings matched at least one rule; per rule:",
               100.0 * (double)any_hits / (double)random_n);
        int never = 0;
        for (int r = 0; r < rs.count; r++) {
            printf("%s %s=%llu", r % 6 ? "" : "\n ", rs.rules[r].id, rule_hits[r]);
            never += rule_hits[r] == 0;
        }
        printf("\n");
        if (never)
            printf("difftest: WARNING: %d rule(s) never matched a random string\n", never);
        for (int r = 0; r < rs.count; r++)
            ast_free(asts[r]);
    }

    printf("difftest: %llu file lines (%d files) + %ld random strings checked, %llu mismatches\n",
           file_lines, nfiles, random_n > 0 ? random_n : 0, mismatches);
    if (mismatches > MAX_PRINT)
        printf("difftest: (only the first %d mismatches were printed)\n", MAX_PRINT);

    posix_free(posix);
    dfa_engine_free(dfa);
    rules_free(&rs);
    if (status)
        return status;
    return mismatches ? 1 : 0;
}
